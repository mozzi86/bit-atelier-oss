function readStoredLang() {
  try {
    const stored = window.localStorage.getItem("lang");
    if (stored && Object.prototype.hasOwnProperty.call(LANGS, stored)) return stored;
  } catch {
    // localStorage nicht verfuegbar -> Default
  }
  return "de";
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(readStoredLang);

  const setLang = useCallback((next) => {
    const value = Object.prototype.hasOwnProperty.call(LANGS, next) ? next : "de";
    setLangState(value);
    try {
      window.localStorage.setItem("lang", value);
    } catch {
      // Persistenz optional
    }
  }, []);

  const t = useCallback(
    (key) => DICT[lang]?.[key] ?? DICT.de[key] ?? key,
    [lang]
  );

  // Screen readers pick pronunciation from <html lang>; index.html ships "de",
  // so without this an English UI would be read out with German rules (A11Y-I18N-12).
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

// Sanfter Fallback ohne Provider: deutsche Texte, kein Crash.
const FALLBACK = {
  lang: "de",
  setLang: () => {},
  t: (key) => DICT.de[key] ?? key,
};

export function useI18n() {
  return useContext(I18nContext) ?? FALLBACK;
}
